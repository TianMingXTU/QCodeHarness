//! 工作区清单的端口：恢复前"工作区有没有被人动过"的检查入口。
//!
//! 放在应用层而不是直接用基础设施的实现：编排器只该问"这份工作区
//! 现在是什么样"，不该知道清单是怎么扫出来的。扫描要碰文件系统，
//! 那属于基础设施的活。

use crate::domain::worktree::WorktreeManifest;

/// 扫描工作区、给出清单。
///
/// 是端口而不是具体类型：测试可以用一个写死的清单，把"工作区被改过"
/// 这个分支稳定地复现出来，不必真的去改文件。
pub trait WorktreeScanner: Send + Sync {
    /// 扫描当前工作区。
    ///
    /// # Errors
    ///
    /// 工作区读不出来时返回说明文本。调用方据此把这次检查降级为
    /// "查不了"而不是"没改动"——两者的后果不同。
    fn scan(&self) -> Result<WorktreeManifest, String>;
}
